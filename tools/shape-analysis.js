#!/usr/bin/env node
// Shape analysis of the rhythm library. Reads js/*.js directly (no build), prints a Markdown report.
//   node tools/shape-analysis.js > RHYTHM_SHAPES.md
// "Shape" = where the onsets fall in the cycle, ignoring instrument, tempo and region.
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.resolve(__dirname, '..');
const ctx = { console, Math, Object, Array, Set, Date, document: {}, navigator: {} }; ctx.window = ctx; vm.createContext(ctx);
for (const f of ['grooves-ableton', 'families', 'rhythms', 'grooves', 'pitch', 'kit', 'shape', 'pattern-groups']) {
  const p = path.join(root, 'js', f + '.js');
  if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, 'utf8'), ctx, { filename: f });
}
const RX = ctx.RX, S = RX.shape;
const fam = (r) => RX.FAMILY_OF[r.id] || r.family;
const famLabel = Object.fromEntries(RX.FAMILIES.map(([id, label]) => [id, label]));
const rows = RX.RHYTHMS.map((r) => {
  const top = r.top, kick = S.fit(r.kick, r.steps);
  const core = RX.coreTop(r);
  // shaped: the core line is trustworthy (right length) and is not an even pulse.
  return { r, top, kick, comp: S.union(kick, top), core, multi: !!(r.topLines && r.topLines.length), shaped: core.from !== 'pulse' && !S.isPulse(core.pattern) };
});
const out = [];
const p = (s = '') => out.push(s);
const group = (keyFn) => { const m = new Map(); rows.forEach((x) => { const k = keyFn(x); if (k) (m.get(k) || m.set(k, []).get(k)).push(x); }); return [...m.entries()].filter(([, v]) => v.length > 1).sort((a, b) => b[1].length - a[1].length); };
const names = (list) => list.map((x) => `${x.r.name} _(${famLabel[fam(x.r)] || fam(x.r)})_`).join(', ');
const crosses = (list) => new Set(list.map((x) => fam(x.r))).size > 1;

p('# Rhythm shapes'); p();
p('Generated by `node tools/shape-analysis.js`. Shape = where onsets fall in the cycle, ignoring instrument, tempo and region.');
p('`x` onset, `.` rest; accents and ghosts are flattened. Patterns are fitted to the row\'s step count.'); p();

p('## 1. Same shape, filed in different families'); p();
p('### 1a. Identical core top line'); p();
p('| Core top | Steps | Rhythms |'); p('|:--|--:|:--|');
group((x) => (!x.shaped ? null : x.r.steps + ':' + S.flat(x.core.pattern))).filter(([, v]) => crosses(v))
  .forEach(([k, v]) => p(`| \`${k.split(':')[1]}\` | ${v[0].r.steps} | ${names(v)} |`));
p();
p('### 1b. Identical composite (kick + core top heard as one line)'); p();
p('The kick changes what a top line means: dembow\'s top over a four-floor kick is a habanera; the same top over a half-time kick is a plain tresillo.'); p();
p('| Composite | Steps | Rhythms |'); p('|:--|--:|:--|');
group((x) => (!x.shaped || S.isPulse(S.union(x.kick, x.core.pattern)) ? null : x.r.steps + ':' + S.union(x.kick, x.core.pattern))).filter(([, v]) => crosses(v))
  .forEach(([k, v]) => p(`| \`${k.split(':')[1]}\` | ${v[0].r.steps} | ${names(v)} |`));
p();
p('### 1c. Same necklace (one is a rotation of the other)'); p();
p('Rotations share every interval but start elsewhere, so they feel related but not the same.'); p();
p('| Intervals | Steps | Rhythms (core top) |'); p('|:--|--:|:--|');
group((x) => (!x.shaped ? null : x.r.steps + ':' + S.necklace(x.core.pattern)))
  .filter(([, v]) => new Set(v.map((x) => S.flat(x.core.pattern))).size > 1)
  .forEach(([k, v]) => p(`| ${S.intervals(k.split(':')[1]).join('-')} | ${v[0].r.steps} | ${v.map((x) => `${x.r.name} \`${S.flat(x.core.pattern)}\``).join(', ')} |`));
p();

p('## 2. Embellishment chains'); p();
p('B contains every onset of A plus more: B is A decorated. Only shaped (non-pulse) patterns with the same step count, at most 3 added onsets.'); p();
p('| Skeleton | Decorated by |'); p('|:--|:--|');
const shaped = rows.filter((x) => x.shaped);
const seen = new Set();
shaped.forEach((a) => {
  const A = S.flat(a.core.pattern); if (seen.has(a.r.steps + A)) return; seen.add(a.r.steps + A);
  const kids = shaped.filter((b) => b.r.steps === a.r.steps && b.core.pattern.length === a.core.pattern.length && S.flat(b.core.pattern) !== A && S.contains(b.core.pattern, A) && S.count(b.core.pattern) - S.count(A) <= 3);
  if (kids.length) p(`| \`${A}\` ${shaped.filter((x) => x.r.steps === a.r.steps && S.flat(x.core.pattern) === A).map((x) => x.r.name).join(' / ')} | ${[...new Map(kids.map((b) => [S.flat(b.core.pattern), b])).values()].map((b) => `${b.r.name} \`${S.flat(b.core.pattern)}\``).join(', ')} |`);
});
p();

p('## 3. Where the core top line comes from'); p();
const bySrc = {}; rows.forEach((x) => { (bySrc[x.core.from] = bySrc[x.core.from] || []).push(x); });
const SRC = { core: 'Authored skeleton (`core` in rhythms.js)', line: 'A part of the ensemble that carries the shape', top: 'The row\'s own top line', pulse: 'Nothing shaped in the data: only even pulses' };
Object.entries(SRC).forEach(([k, label]) => { const v = bySrc[k] || []; p(`- **${label}:** ${v.length}`); });
p();
p('### Ensemble rhythms whose data holds no shape'); p();
p('Every part is an even pulse, copies the kick, or is the wrong length, so the simple version cannot show the structure until a skeleton (`core`) is researched and added.'); p();
(bySrc.pulse || []).filter((x) => x.multi).forEach((x) => p(`- ${x.r.name} (${x.r.steps} steps) — top \`${x.top}\``));
p();
p('### Core line picked from the ensemble'); p();
p('| Rhythm | Core top | Taken from | Was (lead line) |'); p('|:--|:--|:--|:--|');
(bySrc.line || []).forEach((x) => p(`| ${x.r.name} | \`${x.core.pattern}\` | ${x.core.name} | \`${x.top}\` |`));
p();
p('### Authored skeletons'); p();
p('| Rhythm | Core top | Structure |'); p('|:--|:--|:--|');
(bySrc.core || []).forEach((x) => p(`| ${x.r.name} | \`${x.core.pattern}\` | ${x.core.name} |`));
p();

p('## 4. Data problems found'); p();
const bad = [];
RX.RHYTHMS.forEach((r) => {
  if (r.kick.length !== r.steps) bad.push(`${r.name}: kick has ${r.kick.length} steps, row has ${r.steps}`);
  const free = (r.topLines || []).filter((t) => t.loop).map((t) => t.pattern);
  if (r.top.length !== r.steps && !free.includes(r.top)) bad.push(`${r.name}: top has ${r.top.length} steps, row has ${r.steps}`);
  (r.topLines || []).forEach((t) => { if (t.pattern.length !== r.steps && !t.loop) bad.push(`${r.name} / ${t.name}: ${t.pattern.length} steps, row has ${r.steps}`); });
});
p(`${bad.length} patterns differ from their row's step count without being marked \`loop: true\` (a part that is meant to loop on its own length):`); p();
const loops = RX.RHYTHMS.flatMap((r) => (r.topLines || []).filter((t) => t.loop).map((t) => `${r.name} / ${t.name}: \`${t.pattern}\` loops every ${t.pattern.length} against ${r.steps}`));
p('Free-looping parts:'); p(); loops.forEach((l) => p('- ' + l)); p();
bad.forEach((b) => p('- ' + b));
console.log(out.join('\n'));
