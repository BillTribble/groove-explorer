#!/usr/bin/env python3
"""Build js/drumrack-template.js: a Drum Rack skeleton plus one Simpler pad (DrumBranch),
cut from a real Live 12 set so the .als export can clone a working sampler pad per drum sound.

Usage:  python3 py/build_drumrack_template.py "<path to a Live 12 .als that has a Drum Rack of Simplers>"

The source set is only read. Everything that points at the source's files (sample paths,
preset refs, source contexts, choke group, names) is blanked here; app-side export code fills in
names, notes and sample references per pad and renumbers every Pointee/AutomationTarget id.
"""
import base64, gzip, sys, xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'js' / 'drumrack-template.js'


def sv(el, path, value):
    n = el.find(path)
    if n is None:
        raise SystemExit('missing ' + path)
    n.set('Value', str(value))


def blank_file_ref(fr):
    for tag, v in (('RelativePathType', 0), ('RelativePath', ''), ('Path', ''), ('LivePackName', ''),
                   ('LivePackId', ''), ('OriginalFileSize', 0), ('OriginalCrc', 0), ('SourceHint', '')):
        n = fr.find(tag)
        if n is not None:
            n.set('Value', str(v))
    fr.find('Type').set('Value', '1')


def main(src):
    raw = Path(src).read_bytes()
    root = ET.fromstring(gzip.decompress(raw))
    group = branch = None
    for g in root.iter('DrumGroupDevice'):
        for b in g.find('Branches'):
            if b.find('.//OriginalSimpler') is not None:
                group, branch = g, b
                break
        if group is not None:
            break
    if group is None:
        raise SystemExit('no Drum Rack with a Simpler pad in ' + src)

    # Group device: drop every pad, drop preset provenance.
    for b in list(group.find('Branches')):
        group.find('Branches').remove(b)
    group.find('UserName').set('Value', 'Rhythm explorer kit')
    for tag in ('LastPresetRef', 'SourceContext'):
        n = group.find(tag)
        for c in list(n):
            n.remove(c)
        if tag == 'LastPresetRef':
            ET.SubElement(n, 'Value')

    # Pad: no preset provenance, no sample, no choke, one-shot playback.
    for sc in branch.iter('SourceContext'):
        for c in list(sc):
            sc.remove(c)
    for fr in branch.iter('FileRef'):
        blank_file_ref(fr)
    sv(branch, 'BranchInfo/ChokeGroup', 0)
    sv(branch, 'BranchInfo/SendingNote', 60)
    simpler = branch.find('.//OriginalSimpler')
    sv(simpler, 'Globals/PlaybackMode', 1)      # 1 = One-Shot
    sv(simpler, 'Globals/NumVoices', 4)
    part = simpler.find('Player/MultiSampleMap/SampleParts/MultiSamplePart')
    if part is None:
        raise SystemExit('Simpler has no MultiSamplePart')

    tpl = ET.Element('DrumRackTemplate')
    tpl.append(group)
    tpl.append(branch)
    xml = ET.tostring(tpl, encoding='unicode')
    gz = gzip.compress(xml.encode('utf-8'), 9, mtime=0)
    OUT.write_text(
        '// Generated by py/build_drumrack_template.py from a real Live 12 Drum Rack of Simplers. Do not edit.\n'
        'window.RX = window.RX || {};\n'
        'RX.DRUMRACK_TEMPLATE_B64 = "' + base64.b64encode(gz).decode() + '";\n')
    print('wrote', OUT, len(xml), 'bytes xml,', len(gz), 'gz')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
