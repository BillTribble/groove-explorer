#!/usr/bin/env python3
"""Build js/world-land.js: the land outline for the node map's World layout, as one SVG path.

    python3 py/build_world_outline.py land-110m.json

Input: the `land` object of world-atlas's land-110m.json (TopoJSON of Natural Earth 1:110m land, public domain;
https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json). Output coordinates use the same projection as
js/nodemap.js: equirectangular, 1000 units for 360 degrees of longitude, latitude 80N at the top, Antarctica dropped.
"""
import json, sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'js' / 'world-land.js'
U = 1000 / 360            # map units per degree
TOP, BOTTOM = 80, -58     # latitude window


def proj(lon, lat):
    return (lon + 180) * U, (TOP - max(BOTTOM, min(TOP, lat))) * U


def main(src):
    topo = json.loads(Path(src).read_text())
    sx, sy = topo['transform']['scale']
    tx, ty = topo['transform']['translate']
    arcs = []
    for arc in topo['arcs']:                      # quantised, delta-encoded
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    def ring(idx):
        pts = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        return pts

    geoms = topo['objects']['land']['geometries']
    polys = []
    for g in geoms:
        if g['type'] == 'Polygon':
            polys.append(g['arcs'])
        elif g['type'] == 'MultiPolygon':
            polys.extend(g['arcs'])
    parts = []
    for poly in polys:
        for r in poly:
            pts = ring(r)
            if max(lat for _, lat in pts) < BOTTOM:   # Antarctica and the far south
                continue
            # Rings that cross the 180-degree meridian (eastern Russia, Fiji) jump from +180 to -180; unwrap them so
            # they continue past the map edge instead of drawing a line across the whole world.
            unwrapped, prev = [], None
            for lon, lat in pts:
                if prev is not None:
                    while lon - prev > 180: lon -= 360
                    while prev - lon > 180: lon += 360
                unwrapped.append((lon, lat)); prev = lon
            # Bring the ring back so its centre lies on the map (a ring that starts at Chukotka would otherwise put all
            # of Eurasia 360 degrees to the left), and draw any part that hangs past an edge again on the other side.
            # js/nodemap.js clips the land to the map, so the overhangs disappear.
            mean = sum(lon for lon, _ in unwrapped) / len(unwrapped)
            shift = -360 * round(mean / 360)
            lons = [lon + shift for lon, _ in unwrapped]
            copies = [0] + ([360] if min(lons) < -180 else []) + ([-360] if max(lons) > 180 else [])
            for extra in copies:
                xy, last = [], None
                for lon, lat in unwrapped:
                    p = tuple(round(v, 1) for v in proj(lon + shift + extra, lat))
                    if p != last:
                        xy.append(p); last = p
                if len(xy) >= 3:
                    parts.append('M' + 'L'.join(f'{x:g},{y:g}' for x, y in xy) + 'Z')
    d = ''.join(parts)
    OUT.write_text('// Generated by py/build_world_outline.py from Natural Earth 1:110m land (public domain, via world-atlas).\n'
                   '// Equirectangular, 1000 x ' + f'{(TOP - BOTTOM) * U:.0f}' + ' map units, 80N at the top. Do not edit.\n'
                   'window.RX = window.RX || {};\n'
                   f'RX.WORLD_LAND = {{ width: 1000, height: {(TOP - BOTTOM) * U:.1f}, top: {TOP}, path: "{d}" }};\n')
    print('wrote', OUT, len(d), 'chars,', len(parts), 'rings')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
